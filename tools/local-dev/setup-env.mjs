// Creates <project>/.env.local for local development (once). Secrets are generated here and
// written only to that git-ignored file; nothing secret is printed. Run postgres.mjs first, so
// .data/local-dev.json exists. An existing .env.local is never overwritten.
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..", "..");
const envFile = path.join(root, ".env.local");
const configFile = path.join(root, ".data", "local-dev.json");
if (existsSync(envFile)) {
  console.log(".env.local already exists; nothing was changed.");
  process.exit(0);
}
if (!existsSync(configFile)) {
  console.error("Start the local database first: node tools/local-dev/postgres.mjs");
  process.exit(1);
}
const db = JSON.parse(readFileSync(configFile, "utf8"));
const url = `postgres://${db.user}:${encodeURIComponent(db.password)}@127.0.0.1:${db.port}/${db.database}`;
writeFileSync(
  envFile,
  [
    "# Local development only (generated by tools/local-dev/setup-env.mjs). Never commit.",
    `DATABASE_URL=${url}`,
    "DATA_BACKEND=memory",
    "AUTH_ENABLED=true",
    `BETTER_AUTH_SECRET=${randomBytes(32).toString("base64url")}`,
    "BETTER_AUTH_URL=http://localhost:3000",
    "AUTH_SMTP_URL=smtp://127.0.0.1:1025",
    "AUTH_EMAIL_FROM=Property Intelligence (local) <no-reply@localhost>",
    "",
  ].join("\n"),
  { mode: 0o600 },
);
console.log("Created .env.local (local database, generated secret, local SMTP catcher).");
